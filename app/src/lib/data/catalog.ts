/** Resolves a scanned/typed code to a product. Accepts PLU, UPC or SKU. */
export function lookupByCode(code: string): Product | undefined {
  const q = code.trim();
  if (!q) return undefined;
  return PRODUCTS.find((p) => p.plu === q || p.upc === q || p.sku === q);
}

/** Free-text + code search used by the PLU directory's search box. */
export function searchProducts(query: string, products: Product[] = PRODUCTS): Product[] {
  const q = query.trim().toLowerCase();
  if (!q) return products;
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      (p.subtitle?.toLowerCase().includes(q) ?? false) ||
      (p.plu?.includes(q) ?? false) ||
      (p.upc?.includes(q) ?? false) ||
      (p.sku?.includes(q) ?? false),
  );
}
